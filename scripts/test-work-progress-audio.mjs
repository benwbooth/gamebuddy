// Measure actual recorded output over the request-to-answer interval.
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
const [directory] = process.argv.slice(2);
assert(directory.startsWith('/tmp/gamebuddy-realtime-test-'));
const log = readFileSync(directory+'/runtime.log','utf8');
const held=log.match(/\{"type":"test-answer-held","value":true,"at":(\d+)\}/);
const released=log.match(/\{"type":"test-answer-released","value":true,"at":(\d+)\}/);
assert(held&&released, 'Missing controlled wait boundaries');
const recording = Number(readFileSync(directory+'/recording-start-ms','utf8'));
const start = (Number(held[1])-recording)/1000+1, duration = (Number(released[1])-Number(held[1]))/1000-2;
assert(duration >= 32, 'Test did not span a long request');
const output = spawnSync('ffmpeg',['-nostdin','-hide_banner','-ss',String(start),'-t',String(duration),'-i',directory+'/response.wav','-af','silencedetect=noise=-45dB:d=0.15','-f','null','-'],{encoding:'utf8'});
assert.equal(output.status,0,output.stderr);
const gaps=[...output.stderr.matchAll(/silence_duration: ([\d.]+)/g)].map(m=>Number(m[1]));
assert(gaps.length,'No silence intervals found in the recording');
const longest=Math.max(...gaps);
assert(longest>duration-0.25,`Spoken filler interrupted the silent wait: longest silence ${longest.toFixed(2)} of ${duration.toFixed(2)} seconds`);
console.log(`Recorded silent wait: ${duration.toFixed(1)} seconds pending, longest silent gap ${longest.toFixed(2)} seconds.`);
