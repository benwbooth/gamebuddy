wire({type:'turn.done',turn:{id:'backchannel',role:'assistant'}});tick(2000);
output.level=0;
voice.playerSpeech(false);
assert(!speaker.muted,'release playback synchronously before the next audio quantum');tick();
assert(!speaker.muted,'speech detection opens a reply without clicking');
tick(1000);
assert(!speaker.muted,'a muted backchannel during the question cannot discard the real answer');
output.level=0.1;
assert.equal(current.track.enabled,true,'echo-cancelled microphone stays live during the reply');
const samplesDuringReply=activity.filter(e=>e.type==='input-pcm').length;tick(500);
assert(activity.filter(e=>e.type==='input-pcm').length>samplesDuringReply,'player interruptions can reach the local speech detector');
const permits=activity.filter(e=>e.type==='reply-permit').length;
wire({type:'turn.created',turn:{id:'interrupted',role:'assistant'}});
voice.playerSpeech(true);tick();
